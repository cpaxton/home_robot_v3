"""Task-target bridge from a RoboCasa scene into the PandaOmron WBC contract.

The reach adapter answers "can the policy track this EE target?" This module
answers the next question: "can a skill layer derive object/receptacle targets
from the task scene and drive the policy through them?" It is deliberately a
thin bridge:

- object and cabinet poses are read from the RoboCasa env;
- pregrasp/grasp/lift/place/retreat EE targets are generated by position IK on
  the composed Panda arm;
- the task executor issues EE targets and gripper commands, and reports both
  WBC tracking and the env's own task success.

The teacher path uses the same targets with privileged joint PD so a task
failure can be separated from a policy-tracking failure. It is not a benchmark
claim: the scene, base, and grasp geometry are still development inputs.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any

import numpy as np
from scipy.spatial.transform import Rotation

from emet.controller.manipulation.wbc_contract import action_from_normalized_vector
from emet.rl.manipulation.wbc_env import wbc_observation_layout
from emet.rl.manipulation.wbc_robocasa_panda import RoboCasaPandaBackend

_GRIPPER_OPEN = np.asarray((1.0, -1.0), dtype=np.float64)
_GRIPPER_CLOSE = np.asarray((-1.0, 1.0), dtype=np.float64)


@dataclass(frozen=True)
class TaskPoses:
    """One scene's derived task geometry in world coordinates."""

    object_pose: tuple[float, ...]
    object_category: str
    cabinet_name: str
    cabinet_open: bool
    pregrasp_pose: tuple[float, ...]
    grasp_pose: tuple[float, ...]
    lift_pose: tuple[float, ...]
    preplace_pose: tuple[float, ...]
    place_pose: tuple[float, ...]
    retreat_pose: tuple[float, ...]
    pregrasp_q: np.ndarray
    grasp_q: np.ndarray
    lift_q: np.ndarray
    preplace_q: np.ndarray
    place_q: np.ndarray
    retreat_q: np.ndarray


@dataclass
class TaskStep:
    phase: str
    observation: np.ndarray | None
    teacher_action: np.ndarray | None
    action: np.ndarray
    pos_err: float
    quat_err: float
    collision: bool


@dataclass
class TaskResult:
    success: bool
    failure_phase: str
    poses: TaskPoses
    steps: list[TaskStep]
    object_displacement_m: float
    max_object_lift_m: float
    object_inside_cabinet: bool
    gripper_far: bool
    grasped_after_close: bool
    grasped_after_lift: bool
    final_object_pose: tuple[float, ...]
    final_ee_pose: tuple[float, ...]


def _pose7(position: np.ndarray, rotation: Rotation) -> tuple[float, ...]:
    return tuple(float(value) for value in np.r_[np.asarray(position), rotation.as_quat()])


def _as_rotation(pose: tuple[float, ...]) -> Rotation:
    return Rotation.from_quat(np.asarray(pose[3:], dtype=np.float64))


class RoboCasaPandaTask:
    """Derive and execute a counter-to-cabinet task through the WBC backend."""

    def __init__(
        self,
        env: Any,
        backend: RoboCasaPandaBackend,
        *,
        control_dt: float = 0.05,
        max_move_steps: int = 70,
        position_tolerance_m: float = 0.015,
        torso_height: float = 0.30,
    ) -> None:
        self.env = env
        self.backend = backend
        self.control_dt = float(control_dt)
        self.max_move_steps = int(max_move_steps)
        self.position_tolerance_m = float(position_tolerance_m)
        self.torso_height = float(torso_height)
        self.profile = backend.profile
        self.layout = wbc_observation_layout(self.profile)
        self.curr_phase = ""
        self.teacher_mode = True
        self.policy = None

    # ------------------------------------------------------------------
    # Scene geometry
    # ------------------------------------------------------------------
    def _body_pose(self, body_name: str) -> tuple[float, ...]:
        model = self.backend.model
        data = self.backend.data
        body = int(model.body(body_name).id)
        rotation = Rotation.from_matrix(np.asarray(data.xmat[body], dtype=np.float64).reshape(3, 3))
        return _pose7(np.asarray(data.xpos[body], dtype=np.float64), rotation)

    def object_body_name(self) -> str:
        return str(self.env.objects["obj"].root_body)

    def object_pose(self) -> tuple[float, ...]:
        return self._body_pose(self.object_body_name())

    def cabinet_fixture(self) -> Any:
        return self.env.fixture_refs["cab"][0]

    def cabinet_open(self) -> bool:
        try:
            return bool(self.cabinet_fixture().is_open(self.env))
        except Exception:
            return False

    def cabinet_place_position(self) -> np.ndarray:
        """Center of the lowest cabinet shelf, in world coordinates."""
        fixture = self.cabinet_fixture()
        sites = fixture.get_int_sites(relative=True)
        level = sites.get("level0") or sites.get("level1")
        if not level:
            raise ValueError(f"{fixture.name} has no interior shelf sites")
        return np.asarray(fixture.pos, dtype=np.float64) + np.mean(np.asarray(level), axis=0)

    def grasp_orientation(self) -> Rotation:
        """Top-down grasp with the finger-closing axis across the short side."""
        obj_pose = self.object_pose()
        obj_rotation = _as_rotation(obj_pose)
        points = np.asarray(self.env.objects["obj"].get_bbox_points(), dtype=np.float64)
        extents = points.max(axis=0) - points.min(axis=0)
        axis = np.zeros(3, dtype=np.float64)
        axis[int(np.argmax(extents[:2]))] = 1.0
        long_axis = obj_rotation.apply(axis)
        long_axis[2] = 0.0
        if np.linalg.norm(long_axis) < 1e-6:
            long_axis = np.asarray((1.0, 0.0, 0.0))
        long_axis /= np.linalg.norm(long_axis)
        down = np.asarray((0.0, 0.0, -1.0))
        closing = np.cross(down, long_axis)
        closing /= np.linalg.norm(closing)
        return Rotation.from_matrix(np.column_stack((long_axis, closing, down)))

    # ------------------------------------------------------------------
    # IK and pose construction
    # ------------------------------------------------------------------
    def _forward_pose(self, q: np.ndarray) -> tuple[float, ...]:
        self.backend.data.qpos[self.backend._arm_q] = q
        self.env.sim.forward()
        rotation = Rotation.from_matrix(
            np.asarray(self.backend.data.xmat[self.backend._ee_body], dtype=np.float64).reshape(3, 3)
        )
        return _pose7(np.asarray(self.backend.data.xpos[self.backend._ee_body], dtype=np.float64), rotation)

    def _solve_position(self, target: np.ndarray, q0: np.ndarray, *, max_iter: int = 120) -> np.ndarray:
        q = np.asarray(q0, dtype=np.float64).copy()
        target = np.asarray(target, dtype=np.float64)
        for _ in range(max_iter):
            self.backend.data.qpos[self.backend._arm_q] = q
            self.env.sim.forward()
            error = target - np.asarray(self.backend.data.xpos[self.backend._ee_body], dtype=np.float64)
            if np.linalg.norm(error) <= 0.004:
                break
            jacobian = np.asarray(self.backend._numerical_jacobian(q), dtype=np.float64)[:3]
            step = jacobian.T @ np.linalg.solve(
                jacobian @ jacobian.T + 1e-3 * np.eye(3),
                error * 0.5,
            )
            q = np.clip(q + step, self.backend._arm_low, self.backend._arm_high)
        return q

    def _align_grasp_roll(self, q: np.ndarray, long_axis: np.ndarray) -> np.ndarray:
        best_q = np.asarray(q, dtype=np.float64).copy()
        best_score = float("inf")
        for roll in np.linspace(float(self.backend._arm_low[6]), float(self.backend._arm_high[6]), 73):
            candidate = best_q.copy()
            candidate[6] = roll
            self.backend.data.qpos[self.backend._arm_q] = candidate
            self.env.sim.forward()
            rotation = Rotation.from_matrix(
                np.asarray(self.backend.data.xmat[self.backend._ee_body], dtype=np.float64).reshape(3, 3)
            )
            closing = rotation.apply((0.0, 1.0, 0.0))
            approach = rotation.apply((0.0, 0.0, 1.0))
            score = abs(float(np.dot(closing, long_axis))) + abs(float(approach[2]) + 1.0)
            if score < best_score:
                best_score = score
                best_q = candidate
        return best_q

    def build_poses(self, seed: int | None = None) -> TaskPoses:
        """Reset the backend and derive all task poses for the current scene."""
        observation = self.backend.reset(seed=seed)
        del observation
        self.backend.set_torso_target(self.torso_height)
        self.backend.data.qpos[self.backend._torso_q] = self.torso_height
        self.backend.data.qvel[self.backend._torso_v] = 0.0
        self.env.sim.forward()
        q0 = np.asarray(self.backend.data.qpos[self.backend._arm_q], dtype=np.float64).copy()
        obj_pose = self.object_pose()
        obj_position = np.asarray(obj_pose[:3], dtype=np.float64)
        long_axis = self.grasp_orientation().apply((1.0, 0.0, 0.0))
        long_axis[2] = 0.0
        long_axis /= np.linalg.norm(long_axis)

        grasp_q = self._solve_position(obj_position + np.asarray((0.0, 0.0, 0.108)), q0)
        grasp_q = self._align_grasp_roll(grasp_q, long_axis)
        pregrasp_q = self._solve_position(obj_position + np.asarray((0.0, 0.0, 0.20)), q0)
        pregrasp_q[6] = grasp_q[6]
        lift_q = self._solve_position(obj_position + np.asarray((0.0, 0.0, 0.32)), grasp_q)
        lift_q[6] = grasp_q[6]

        place_position = self.cabinet_place_position() + np.asarray((0.0, 0.0, 0.05))
        preplace_position = place_position + np.asarray((0.0, -0.22, 0.05))
        preplace_q = self._solve_position(preplace_position, q0)
        place_q = self._solve_position(place_position, preplace_q)
        retreat_q = self._solve_position(place_position + np.asarray((0.0, -0.18, 0.10)), place_q)

        poses = TaskPoses(
            object_pose=obj_pose,
            object_category=str(self.env.object_cfgs[0].get("info", {}).get("cat") or "object"),
            cabinet_name=str(self.cabinet_fixture().name),
            cabinet_open=self.cabinet_open(),
            pregrasp_pose=self._forward_pose(pregrasp_q),
            grasp_pose=self._forward_pose(grasp_q),
            lift_pose=self._forward_pose(lift_q),
            preplace_pose=self._forward_pose(preplace_q),
            place_pose=self._forward_pose(place_q),
            retreat_pose=self._forward_pose(retreat_q),
            pregrasp_q=pregrasp_q,
            grasp_q=grasp_q,
            lift_q=lift_q,
            preplace_q=preplace_q,
            place_q=place_q,
            retreat_q=retreat_q,
        )
        # Leave the arm at the pregrasp pose so callers can start the task
        # without another reset boundary.
        self.backend.data.qpos[self.backend._arm_q] = pregrasp_q
        self.backend._target_q = None
        self.backend.set_ee_target(poses.pregrasp_pose)
        self.env.sim.forward()
        return poses

    # ------------------------------------------------------------------
    # Execution
    # ------------------------------------------------------------------
    def configure(self, *, teacher: bool, policy=None) -> None:
        self.teacher_mode = bool(teacher)
        self.policy = policy

    def _set_phase(self, phase: str, q: np.ndarray, pose: tuple[float, ...], *, joint: bool = False) -> None:
        self.curr_phase = phase
        self.backend._target_q = None
        self.backend.set_ee_target(pose)
        if self.teacher_mode and joint:
            # Use joint PD for targets that sit near the arm's Cartesian limits.
            self.backend._target_q = np.asarray(q, dtype=np.float64).copy()
        elif not self.teacher_mode:
            # Keep a privileged joint target only as the DAgger label source.
            self.backend._target_q = np.asarray(q, dtype=np.float64).copy()

    def _centered_grasp_pose(self) -> tuple[float, ...]:
        """Shift the grasp target to center the object between the fingers."""
        data = self.backend.data
        ee = np.asarray(data.xpos[self.backend._ee_body], dtype=np.float64)
        rotation = Rotation.from_matrix(np.asarray(data.xmat[self.backend._ee_body], dtype=np.float64).reshape(3, 3))
        object_position = np.asarray(data.xpos[self.env.obj_body_id["obj"]], dtype=np.float64)
        local = rotation.as_matrix().T @ (object_position - ee)
        local[2] = 0.0
        return _pose7(ee + rotation.apply(local), rotation)

    def _step_action(self, observation: np.ndarray | None, gripper: np.ndarray) -> TaskStep:
        if self.teacher_mode:
            action = np.asarray(self.backend.teacher_action(), dtype=np.float64)
        else:
            assert self.policy is not None
            import torch

            with torch.no_grad():
                action = (
                    self.policy.deterministic_action(torch.as_tensor(observation, dtype=torch.float32).unsqueeze(0))[0]
                    .cpu()
                    .numpy()
                    .astype(np.float64)
                )
        action[-2:] = gripper
        teacher_action = np.asarray(self.backend.teacher_action(), dtype=np.float64)
        contract_action = action_from_normalized_vector(action, self.profile)
        command = self.backend.preferred_adapter.command(contract_action, self.backend._observation())
        next_observation, terminated, info = self.backend.step(command, self.control_dt)
        terms = self.backend._observation().arms[0]
        target = terms.ee_target
        if target is None:
            pos_err = float("nan")
            quat_err = float("nan")
        else:
            pos_err = float(np.linalg.norm(np.asarray(terms.ee_pose[:3]) - np.asarray(target[:3])))
            quat_err = float(
                (
                    Rotation.from_quat(np.asarray(terms.ee_pose[3:], dtype=np.float64))
                    * Rotation.from_quat(np.asarray(target[3:], dtype=np.float64)).inv()
                ).magnitude()
            )
        observation = self.layout.encode(next_observation) if not self.teacher_mode else None
        step = TaskStep(
            phase=self.curr_phase,
            observation=observation,
            teacher_action=teacher_action,
            action=action,
            pos_err=pos_err,
            quat_err=quat_err,
            collision=bool(info.get("collision", False)),
        )
        return step, bool(terminated)

    def _move(
        self,
        phase: str,
        q: np.ndarray,
        pose: tuple[float, ...],
        gripper: np.ndarray,
        *,
        joint: bool = False,
    ) -> list[TaskStep]:
        self._set_phase(phase, q, pose, joint=joint)
        steps: list[TaskStep] = []
        observation = self.layout.encode(self.backend._observation()) if not self.teacher_mode else None
        for _ in range(self.max_move_steps):
            step, terminated = self._step_action(observation, gripper)
            steps.append(step)
            observation = step.observation
            if step.collision or terminated:
                break
            if np.isfinite(step.pos_err) and step.pos_err <= self.position_tolerance_m:
                # Hold briefly so the target is actually settled.
                for _ in range(4):
                    step, terminated = self._step_action(observation, gripper)
                    steps.append(step)
                    observation = step.observation
                    if step.collision or terminated:
                        break
                break
        return steps

    def _grasped(self) -> bool:
        try:
            from robocasa.utils.object_utils import check_obj_grasped

            return bool(check_obj_grasped(self.env, "obj"))
        except Exception:
            return False

    def _task_parts(self) -> tuple[bool, bool]:
        try:
            from robocasa.utils.object_utils import gripper_obj_far, obj_inside_of

            inside = bool(obj_inside_of(self.env, "obj", self.env.cab))
            far = bool(gripper_obj_far(self.env))
            return inside, far
        except Exception:
            return False, False

    def execute(self, *, teacher: bool = True, policy=None, seed: int | None = None) -> TaskResult:
        """Run one scripted counter-to-cabinet attempt through the WBC backend."""
        self.configure(teacher=teacher, policy=policy)
        poses = self.build_poses(seed=seed)
        if not poses.cabinet_open:
            return TaskResult(
                success=False,
                failure_phase="cabinet_closed",
                poses=poses,
                steps=[],
                object_displacement_m=0.0,
                max_object_lift_m=0.0,
                object_inside_cabinet=False,
                gripper_far=False,
                grasped_after_close=False,
                grasped_after_lift=False,
                final_object_pose=poses.object_pose,
                final_ee_pose=poses.pregrasp_pose,
            )
        steps: list[TaskStep] = []
        initial_z = float(poses.object_pose[2])
        max_lift = 0.0
        grasped_after_close = False
        grasped_after_lift = False
        steps += self._move("pregrasp", poses.pregrasp_q, poses.pregrasp_pose, _GRIPPER_OPEN)
        steps += self._move("grasp", poses.grasp_q, poses.grasp_pose, _GRIPPER_OPEN)
        for _ in range(2):
            center_pose = self._centered_grasp_pose()
            center_q = self._solve_position(
                np.asarray(center_pose[:3], dtype=np.float64),
                self.backend.data.qpos[self.backend._arm_q],
            )
            steps += self._move("grasp_center", center_q, center_pose, _GRIPPER_OPEN)
        # Close in place.
        steps += self._move("close", poses.grasp_q, poses.grasp_pose, _GRIPPER_CLOSE)
        grasped_after_close = self._grasped()
        max_lift = max(max_lift, float(self.object_pose()[2]) - initial_z)
        steps += self._move("lift", poses.lift_q, poses.lift_pose, _GRIPPER_CLOSE)
        grasped_after_lift = self._grasped()
        max_lift = max(max_lift, float(self.object_pose()[2]) - initial_z)
        steps += self._move("preplace", poses.preplace_q, poses.preplace_pose, _GRIPPER_CLOSE, joint=True)
        max_lift = max(max_lift, float(self.object_pose()[2]) - initial_z)
        steps += self._move("place", poses.place_q, poses.place_pose, _GRIPPER_CLOSE, joint=True)
        steps += self._move("release", poses.place_q, poses.place_pose, _GRIPPER_OPEN, joint=True)
        steps += self._move("retreat", poses.retreat_q, poses.retreat_pose, _GRIPPER_OPEN, joint=True)

        final_object = self.object_pose()
        displacement = float(np.linalg.norm(np.asarray(final_object[:3]) - np.asarray(poses.object_pose[:3])))
        success = bool(self.env._check_success())
        inside, far = self._task_parts()
        failure_phase = ""
        if not success:
            bad = [
                step.phase
                for step in steps
                if step.collision or (np.isfinite(step.pos_err) and step.pos_err > self.position_tolerance_m)
            ]
            failure_phase = bad[-1] if bad else "task_failed"
        return TaskResult(
            success=success,
            failure_phase=failure_phase,
            poses=poses,
            steps=steps,
            object_displacement_m=displacement,
            max_object_lift_m=float(max_lift),
            object_inside_cabinet=inside,
            gripper_far=far,
            grasped_after_close=grasped_after_close,
            grasped_after_lift=grasped_after_lift,
            final_object_pose=final_object,
            final_ee_pose=self._forward_pose(np.asarray(self.backend.data.qpos[self.backend._arm_q])),
        )


